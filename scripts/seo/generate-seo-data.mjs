// Build-time SEO data generator (SEO v1.2, 019fe47c)
// Fetches published WP posts and writes:
//  - src/data/blog-articles.ts   (slug -> title/description/dates/url for SeoManager)
//  - public/sitemap.xml          (refreshes /blog/<slug> entries, keeps base entries)
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const API = "https://keys-starter.com/wp-json/wp/v2/posts?per_page=100&status=publish&_fields=slug,title,date,modified,excerpt,link";

function decodeHtml(s) {
  if (!s) return "";
  return s
    .replace(/<[^>]+>/g, "")
    .replace(/&amp;/g, "&")
    .replace(/&#0?38;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#8217;/g, "\u2019")
    .replace(/&#8216;/g, "\u2018")
    .replace(/&#8220;/g, "\u201c")
    .replace(/&#8221;/g, "\u201d")
    .replace(/&#8211;/g, "\u2013")
    .replace(/&#8212;/g, "\u2014")
    .replace(/&nbsp;/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function truncate(s, n) {
  if (s.length <= n) return s;
  return s.slice(0, n - 1).replace(/[^a-zA-Z0-9\u4e00-\u9fa5 ]$/, "") + "\u2026";
}

async function fetchPosts() {
  const res = await fetch(API, { headers: { "User-Agent": "Mozilla/5.0 (KeyStarter SEO build script)" } });
  if (!res.ok) throw new Error("WP posts fetch failed: " + res.status);
  return res.json();
}

function buildTs(articles) {
  const lines = [
    "// Generated by scripts/seo/generate-seo-data.mjs - do not edit manually.",
    "export interface BlogArticle {",
    "  title: string;",
    "  description: string;",
    "  datePublished: string;",
    "  dateModified: string;",
    "  url: string;",
    "}",
    "",
    "export const BLOG_ARTICLES: Record<string, BlogArticle> = {",
  ];
  for (const a of articles) {
    lines.push(
      `  ${JSON.stringify(a.slug)}: { title: ${JSON.stringify(a.title)}, description: ${JSON.stringify(a.description)}, datePublished: ${JSON.stringify(a.datePublished)}, dateModified: ${JSON.stringify(a.dateModified)}, url: ${JSON.stringify(a.url)} },`
    );
  }
  lines.push("};", "");
  return lines.join("\n");
}

function buildSitemap(baseXml, articles) {
  const base = baseXml.replace(/[\s\S]*<urlset[^>]*>/, "").replace(/<\/urlset>\s*$/, "");
  const blocks = [];
  for (const block of base.matchAll(/<url>[\s\S]*?<\/url>/g)) {
    const b = block[0];
    if (!/https:\/\/keys-starter\.com\/blog\/[a-z0-9-]+/.test(b)) blocks.push(b);
  }
  const articleBlocks = articles.map(
    (a) =>
      `<url><loc>${a.url}</loc><lastmod>${a.dateModified.slice(0, 10)}</lastmod><priority>0.6</priority></url>`
  );
  const xml =
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    blocks.join("\n") +
    (blocks.length && articleBlocks.length ? "\n" : "") +
    articleBlocks.join("\n") +
    "\n</urlset>\n";
  return xml;
}

const posts = await fetchPosts();
const articles = posts.map((p) => ({
  slug: p.slug,
  title: decodeHtml(p.title?.rendered) || p.slug,
  description: truncate(decodeHtml(p.excerpt?.rendered) || p.title?.rendered || "", 155),
  datePublished: p.date,
  dateModified: p.modified,
  url: "https://keys-starter.com/blog/" + p.slug,
}));

writeFileSync(path.join(ROOT, "src", "data", "blog-articles.ts"), buildTs(articles), "utf8");

const sitemapPath = path.join(ROOT, "public", "sitemap.xml");
const baseXml = existsSync(sitemapPath) ? readFileSync(sitemapPath, "utf8") : "";
const sitemapXml = buildSitemap(baseXml, articles);
writeFileSync(sitemapPath, sitemapXml, "utf8");

console.log(`[seo-gen] articles=${articles.length} sitemap_urls=${sitemapXml.match(/<url>/g).length}`);
